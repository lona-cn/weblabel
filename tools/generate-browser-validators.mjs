import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { browserContractNames } from '../packages/contracts/src/browser-contracts.js';
import { numericFormats } from '../packages/contracts/src/numeric-formats.js';

const contractsDirectory = new URL('../packages/contracts/', import.meta.url);
const outputFile = new URL('src/browser-validators.generated.js', contractsDirectory);
const normalizeLineEndings = (text) => text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');

async function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('usage: node tools/generate-browser-validators.mjs [--check]');
  }
  const check = args.length === 1;
  // Resolve tools from their owning package, not a hoisted root or retired host.
  const require = createRequire(new URL('package.json', contractsDirectory));
  const Ajv = require('ajv');
  const standaloneCode = require('ajv/dist/standalone/index.js');
  const { _ } = require('ajv/dist/compile/codegen/index.js');
  const { build } = require('esbuild');
  const ajv = new Ajv({
    allErrors: true,
    strict: false,
    code: { source: true, esm: true, formats: _`numericFormats` },
  });
  for (const [name, format] of Object.entries(numericFormats)) ajv.addFormat(name, format);
  // In particular, do not add date-time: the existing browser validator ignores
  // that unknown format. AJV's build-time warnings remain visible.
  const exports = {};
  for (const name of browserContractNames) {
    const schema = JSON.parse(await readFile(new URL(`generated/${name}.schema.json`, contractsDirectory), 'utf8'));
    ajv.addSchema(schema, name);
    exports[name] = name;
  }
  const standalone = standaloneCode(ajv, exports);
  const result = await build({
    absWorkingDir: fileURLToPath(contractsDirectory),
    stdin: {
      contents: `import { numericFormats } from './src/numeric-formats.js';\n${standalone}`,
      sourcefile: 'browser-validators.standalone.js',
      resolveDir: fileURLToPath(contractsDirectory),
      loader: 'js',
    },
    bundle: true,
    platform: 'browser',
    format: 'esm',
    target: 'es2022',
    write: false,
    // Remove path comments as well as absolute build paths from the artifact.
    minify: true,
    legalComments: 'eof',
    sourcemap: false,
    banner: { js: '// Generated by tools/generate-browser-validators.mjs. Do not edit.' },
  });
  // esbuild resolves standalone AJV runtime helpers into this browser ESM;
  // neither the compiler nor schema JSON imports are shipped to the browser.
  const generated = normalizeLineEndings(result.outputFiles[0].text);
  if (check) {
    let committed;
    try {
      committed = await readFile(outputFile, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      throw new Error('browser validators are missing; run pnpm contracts:generate');
    }
    if (normalizeLineEndings(committed) !== generated) {
      throw new Error('browser validators differ; run pnpm contracts:generate');
    }
  } else {
    await writeFile(outputFile, generated);
  }
}

main().catch((error) => {
  console.error(`browser validator generation failed: ${error.message}`);
  process.exitCode = 1;
});
