import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const output = new URL('./', import.meta.url);
const browser = await chromium.launch({ executablePath: chromium.executablePath(), headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 1100 } });
  const page = await context.newPage(); const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5198/reports/T24/ux-improvement/ux23-binding-ui/surface.html');
  await expect(page.getByText(/controlled HTTP fixture · not live data/)).toBeVisible();
  await expect(page.getByText(/没有可归属于此 run 的工时记录/)).toBeVisible();
  await expect(page.getByTestId('activity-opt-in')).not.toBeChecked();
  await expect(page.getByTestId('activity-task-binding')).not.toBeChecked();
  await expect(page.getByTestId('activity-run-binding')).toHaveValue('');
  const evidence = () => page.request.get('http://127.0.0.1:5198/fixture-evidence').then(response => response.json());
  expect((await evidence()).requests.every(item => item.method === 'GET')).toBe(true);
  await page.getByTestId('activity-opt-in').check();
  await page.getByRole('textbox', { name: '本地工作输入' }).fill('synthetic content is never recorded');
  await page.getByTestId('activity-task-binding').check();
  await page.getByTestId('activity-run-binding').selectOption('fixture-run');
  await page.waitForTimeout(180);
  await page.evaluate(() => window.ux23Collector.commit());
  const bound = await page.evaluate(() => window.ux23Collector.snapshot());
  expect(bound[0].intervals.some(item => item.task_id === 'fixture-task' && item.run_id === 'fixture-run' && item.duration_ms > 0)).toBe(true);
  expect(JSON.stringify(bound)).not.toContain('synthetic content');
  expect((await evidence()).requests.some(item => item.method === 'PUT')).toBe(false);
  await page.getByTestId('activity-publish').click();
  await expect(page.getByText('本人工时已保存到项目服务器。')).toBeVisible();
  await page.getByRole('button', { name: '只读重新检查结果摘要' }).click();
  await expect(page.getByText(/本人明确关联运行与任务的自愿区间/)).toBeVisible();
  await expect(page.getByRole('link', { name: /查看匹配的保存版本/ })).toHaveAttribute('href', '/?project_id=fixture-project&asset_revision_id=fixture-asset&ontology_version_id=fixture-ontology&annotation_revision_id=fixture-saved');
  await expect(page.getByText(/采纳后当前对象已有变化（归因未知）/)).toBeAttached();
  await page.screenshot({ path: new URL('bound-outcome.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  await page.getByRole('button', { name: '切换图片范围' }).click();
  await expect(page.getByTestId('activity-task-binding')).not.toBeChecked();
  await expect(page.getByTestId('activity-run-binding')).toHaveValue('');
  await expect(page.getByTestId('activity-run-binding')).toBeDisabled();
  expect(await page.evaluate(() => window.ux23Collector.getBinding())).toEqual({});
  await page.getByRole('button', { name: '切换图片范围' }).click();
  await expect(page.getByTestId('activity-run-binding')).toHaveValue('');
  await page.getByTestId('activity-task-binding').check();
  await page.getByTestId('activity-run-binding').selectOption('fixture-run');
  await page.getByRole('button', { name: '切换已知运行' }).click();
  await expect(page.getByTestId('activity-task-binding')).not.toBeChecked();
  await expect(page.getByTestId('activity-run-binding')).toHaveValue('');
  const beforeReload = await page.evaluate(() => window.ux23Collector.snapshot());
  await page.reload();
  await expect(page.getByTestId('activity-opt-in')).not.toBeChecked();
  await expect(page.getByTestId('activity-task-binding')).not.toBeChecked();
  await expect(page.getByTestId('activity-run-binding')).toHaveValue('');
  const restored = await page.evaluate(() => window.ux23Collector.snapshot());
  expect(restored[0].intervals.slice(0, bound[0].intervals.length)).toEqual(bound[0].intervals);
  expect(restored[0].intervals.slice(0, beforeReload[0].intervals.length)).toEqual(beforeReload[0].intervals);
  expect(restored[0].version).toBe(beforeReload[0].version);
  await page.screenshot({ path: new URL('restored-default-off.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  expect(errors).toEqual([]);
  const http = await evidence(); expect(http.requests.filter(item => item.method === 'PUT')).toHaveLength(1);
  await writeFile(new URL('browser-evidence.json', output), JSON.stringify({ evidence_kind: 'controlled_http_fixture_not_live', browser: browser.version(), assertions: ['default off', 'explicit task and exact pinned run binding', 'real monotonic time', 'no input contents', 'no automatic PUT', 'explicit publish and ACK', 'exact visual revision URI', 'unknown object attribution', 'cross-scope/stale pins reset', 'run change reset', 'real localStorage restore preserving prefix'], errors, http, bound, restored }, null, 2));
  console.log('PASS actual Chromium ActivityPanel + OutcomeSummary smoke; controlled HTTP fixture, not live data; all assertions passed');
} finally { await browser.close(); }
